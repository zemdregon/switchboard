/** What must not survive in any sanitised message. */
const LEFTOVERS = [
  /co-?authored/iu,
  /generated[- ](?:by|with)/iu,
  /assisted-by/iu,
  /claude/iu,
  /anthropic/iu,
  /codex/iu,
  /chatgpt/iu,
  /session/iu,
  /sess_[0-9A-Za-z]{26}/u,
  /run_[0-9A-Za-z]{26}/u,
  /claude\.ai|chatgpt\.com|claude\.com/iu,
  /abcdef123456/u,
];

describe("built-in sanitiser rules (FR-GIT-04, LLD §12.4)", () => {
  for (const f of FIXTURES) {
    it(`leaves no attribution or identifier: ${f.name}`, () => {
      const r = sanitizeMessage(f.message);
      expect(r.message).toBe(f.keeps);
      for (const re of LEFTOVERS) expect(r.message, String(re)).not.toMatch(re);
      expect(Object.keys(r.report.rules).length).toBeGreaterThan(0);
      expect(JSON.stringify(r.report)).not.toMatch(/claude|codex|sess_|chatgpt|http/iu); // counts only, never text
    });
  }

  it("is idempotent: sanitising the output changes nothing and reports nothing", () => {
    for (const f of FIXTURES) {
      const once = sanitizeMessage(f.message);
      const twice = sanitizeMessage(once.message);
      expect(twice.message).toBe(once.message);
      expect(twice.report.rules).toEqual({});
    }
  });

  it("reports counts per rule id", () => {
    const r = sanitizeMessage(
      `Subject\n\nCo-authored-by: A\nCo-authored-by: B\nGenerated with Claude Code\n${SESSION} and ${RUN}`,
    );
    expect(r.report.rules).toEqual({ "footer.generated-by": 1, "id.controller": 2, "trailer.co-author": 2 });
  });

  it("removes the run's provider-native session id by exact match and ignores short ids", () => {
    const native = "thread_7f3a9c21d0e84b";
    const s = createSanitizer({ nativeSessionIds: [native, "abc"] });
    const r = s.sanitize(`Retry on 429 (${native})\n\nabc stays`);
    expect(r.message).toBe("Retry on 429 ()\n\nabc stays");
    expect(r.report.rules).toEqual({ "id.native-session": 1 });
  });

  it("keeps ordinary messages byte for byte, apart from trailing blanks and blank-line runs", () => {
    const msg =
      "Add `Cursor` type for pagination\n\n- one\n- two\n\nSee https://docs.example.com/api/v1/cursor.\nFixes #123";
    expect(sanitizeMessage(msg).message).toBe(msg);
    expect(sanitizeMessage("a\n\n\n\nb  \n\n").message).toBe("a\n\nb");
  });

  it("does not remove documentation links on provider hosts", () => {
    const msg = "Link the API docs\n\nhttps://docs.anthropic.com/en/api/messages";
    expect(sanitizeMessage(msg).message).toBe(msg);
  });

  it("returns an empty message when nothing is left, and never adds a line", () => {
    expect(sanitizeMessage("Co-authored-by: Claude <noreply@anthropic.com>").message).toBe("");
    expect(sanitizeMessage("x").message).toBe("x");
  });

  it("refuses an over-long message", () => {
    expect(() => sanitizeMessage("a".repeat(70_000))).toThrow(SanitizerError);
  });
});

describe("operator patterns (FR-GIT-04; safe subset)", () => {
  it("removes matching lines, case-insensitively, and reports operator.<n> counts", () => {
    const s = createSanitizer({ operatorPatterns: ["^ticket-\\d{1,6}\\b", "internal\\.corp\\.example"] });
    const r = s.sanitize("Fix cache\n\nTICKET-4411 is the tracker\nsee wiki.internal.corp.example/x\nKeep this");
    expect(r.message).toBe("Fix cache\n\nKeep this");
    expect(r.report.rules).toEqual({ "operator.1": 1, "operator.2": 1 });
  });

  it("applies to long lines in windows and stays inside the budget", () => {
    const s = createSanitizer({ operatorPatterns: [".*foobar"] });
    const started = Date.now();
    s.sanitize(`${"a".repeat(8000)}\n${"foo".repeat(1000)}`);
    expect(Date.now() - started).toBeLessThan(1500);
  });

  it("fails closed when the budget is exhausted", () => {
    let t = 0;
    const s = createSanitizer({ operatorPatterns: ["secret"], budgetMs: 5, now: () => (t += 10) });
    expect(() => s.sanitize("hello")).toThrow(/budget/u);
  });

  it("accepts the documented safe forms", () => {
    for (const p of [
      "^ticket-\\d{1,6}$",
      "internal\\.corp",
      "(?:foo|bar)?baz",
      "[a-z0-9_-]{3,16}\\s*:",
      "a+b",
      "x{2,}y?",
      ".*foo",
      "[a-z]{1,64}[0-9]{1,64}x",
    ]) {
      expect(() => compileOperatorPattern(p), p).not.toThrow();
    }
  });

  it("rejects pathological and unsupported patterns", () => {
    const bad: [string, RegExp][] = [
      ["(a+)+$", /quantified group/u],
      ["(a*)*", /quantified group/u],
      ["(a|a)*b", /quantified group/u],
      ["(?:a|aa)+", /quantified group/u],
      ["((a|b)c)+", /quantified group/u],
      [".*a.*b", /unbounded quantifiers/u],
      [".*.*.*x", /unbounded quantifiers/u],
      ["a+b+", /unbounded quantifiers/u],
      ["x{2,}y+", /unbounded quantifiers/u],
      ["[a-z]{1,64}[a-z]{1,64}[a-z]{1,64}x", /too expensive/u],
      [".*[a-z]{1,64}[0-9]{1,2}", /too expensive/u],
      ["(a)\\1", /back-references/u],
      ["(?<n>a)\\k<n>", /only \(\?: \)/u],
      ["foo(?=bar)", /only \(\?: \)/u],
      ["(?<!foo)bar", /only \(\?: \)/u],
      ["\\p{L}+", /Unicode property/u],
      ["a{1,1000}", /repeat count/u],
      ["a{5,2}", /m < n/u],
      ["*a", /nothing to repeat/u],
      ["a**", /nothing to repeat/u],
      ["(unclosed", /unbalanced/u],
      ["closed)", /unbalanced/u],
      ["[abc", /unterminated/u],
      ["[]", /empty character class/u],
      ["a\nb", /line break/u],
      ["", /non-empty/u],
      ["a".repeat(MAX_PATTERN_LENGTH + 1), /longer than/u],
    ];
    for (const [p, why] of bad) {
      expect(() => compileOperatorPattern(p), p).toThrow(PatternError);
      expect(() => compileOperatorPattern(p), p).toThrow(why);
    }
  });

  it("validates a list: count limit and per-index messages", () => {
    expect(validateOperatorPatterns(["ok", "(a+)+"])).toEqual([expect.stringMatching(/^\[1\]: /u)]);
    expect(validateOperatorPatterns(Array.from({ length: MAX_PATTERNS + 1 }, () => "x"))[0]).toMatch(/at most/u);
  });

  it("createSanitizer rejects an invalid pattern with INVALID_PATTERN", () => {
    expect(() => createSanitizer({ operatorPatterns: ["(a+)+"] })).toThrow(/pattern 0/u);
    try {
      createSanitizer({ operatorPatterns: ["(a+)+"] });
    } catch (err) {
      expect((err as SanitizerError).code).toBe("INVALID_PATTERN");
    }
  });

  it("the worst accepted pattern on a window-sized line is fast (quadratic bound holds)", () => {
    const re = compileOperatorPattern(".*[a-z]{1,64}b");
    const line = "a".repeat(PATTERN_WINDOW);
    const started = Date.now();
    re.test(line);
    expect(Date.now() - started).toBeLessThan(1500);
    expect(PATTERN_WINDOW).toBe(1024);
  });
});
